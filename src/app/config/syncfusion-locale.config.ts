/**
 * Función principal para cambiar el idioma de Syncfusion
 * Llama a esta desde tu botón existente
 */
export function changeSyncfusionLanguage(language: 'es' | 'en'): void {
    // 1. Cambiar cultura de Syncfusion
    setCulture(language);

    // 2. Cargar recursos de texto
    L10n.load(syncfusionLocaleResources[language]);

    // 3. Guardar preferencia en localStorage
    localStorage.setItem('syncfusion-lang', language);
}

/**
 * Obtiene el idioma preferido del usuario
 * 1. localStorage 'lang' (tu i18n)
 * 2. localStorage 'preferredLanguage' (alternativo)
 * 3. Idioma del navegador
 * 4. Español por defecto
 */
export function getPreferredLanguage(): 'es' | 'en' {
    // Prioridad 1: Tu i18n existente
    const i18nLang = localStorage.getItem('lang');
    if (i18nLang === 'es' || i18nLang === 'en') {
        return i18nLang;
    }

    // Prioridad 2: Syncfusion específico
    const syncfusionLang = localStorage.getItem('syncfusion-lang');
    if (syncfusionLang === 'es' || syncfusionLang === 'en') {
        return syncfusionLang;
    }

    // Prioridad 3: Preferencia general
    const preferredLang = localStorage.getItem('preferredLanguage');
    if (preferredLang === 'es' || preferredLang === 'en') {
        return preferredLang;
    }

    // Prioridad 4: Navegador
    const browserLang = navigator.language.split('-')[0];
    if (browserLang === 'es' || browserLang === 'en') {
        return browserLang;
    }

    // Por defecto
    return 'es';
}

/**
 * Inicializa Syncfusion con el idioma guardado
 * Llama a esta en main.ts al iniciar la app
 */
export function initializeSyncfusionOnAppStart(): void {
    const language = getPreferredLanguage();
    changeSyncfusionLanguage(language);
}

/**
 * Sincroniza Syncfusion con tu i18n existente
 * Útil si cambias idioma desde otro lugar
 */
export function syncWithI18n(): void {
    const i18nLang = localStorage.getItem('lang');
    if (i18nLang === 'es' || i18nLang === 'en') {
        changeSyncfusionLanguage(i18nLang);
    }
}

export function loadSyncfusionLocale(language: string = 'es') {
    const lang = language.split('-')[0]; // Convertir 'es-ES' a 'es'
    const locale = lang === 'es' || lang === 'en' ? lang : 'es';

    L10n.load(syncfusionLocaleResources[locale]);
}